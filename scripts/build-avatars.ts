/**
 * Build square WebP avatars from sources in /workspace/avatar-src.
 * Drop linkedin.jpg in /workspace/avatar-src and run npm run avatars.
 */
import { existsSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const SOURCE_DIR = "/workspace/avatar-src";
const OUTPUT_DIR = path.resolve(process.cwd(), "public", "avatar");
const WEBP_QUALITY = 82;
const SIZE_FULL = 480;
const SIZE_SMALL = 240;

export const AVATAR_SOURCES = [
  { name: "github", files: ["github.png", "github.jpg", "github.webp"] },
  { name: "linkedin", files: ["linkedin.jpg", "linkedin.png", "linkedin.webp"] },
] as const;

export function resolveAvatarSource(files: readonly string[]): string | null {
  for (const file of files) {
    const candidate = path.join(SOURCE_DIR, file);
    if (existsSync(candidate)) {
      return candidate;
    }
  }
  return null;
}

export function avatarOutputName(name: string, size: number): string {
  return size === SIZE_FULL ? `${name}.webp` : `${name}-${size}.webp`;
}

export async function writeAvatarVariants(
  inputPath: string,
  name: string,
): Promise<string[]> {
  await mkdir(OUTPUT_DIR, { recursive: true });
  const written: string[] = [];

  for (const size of [SIZE_FULL, SIZE_SMALL] as const) {
    const filename = avatarOutputName(name, size);
    const outputPath = path.join(OUTPUT_DIR, filename);
    await sharp(inputPath)
      .rotate()
      .resize(size, size, { fit: "cover", position: "centre" })
      .webp({ quality: WEBP_QUALITY })
      .toFile(outputPath);
    written.push(outputPath);
  }

  return written;
}

export async function writeAvatarManifest(names: readonly string[]): Promise<void> {
  const available = AVATAR_SOURCES.map((source) => source.name).filter(
    (name) =>
      names.includes(name) ||
      existsSync(path.join(OUTPUT_DIR, avatarOutputName(name, SIZE_FULL))),
  );
  const body = `/** Generated by scripts/build-avatars.ts. */\nexport const generatedAvatarNames = ${JSON.stringify(available)} as const;\n`;
  await writeFile(
    path.resolve(process.cwd(), "src/lib/seed/avatarManifest.ts"),
    body,
  );
}

export async function buildAvatars(): Promise<string[]> {
  const written: string[] = [];
  const names: string[] = [];

  for (const source of AVATAR_SOURCES) {
    const inputPath = resolveAvatarSource(source.files);
    if (!inputPath) {
      continue;
    }
    names.push(source.name);
    written.push(...(await writeAvatarVariants(inputPath, source.name)));
  }

  await writeAvatarManifest(names);
  return written;
}

async function main(): Promise<void> {
  const written = await buildAvatars();
  if (written.length === 0) {
    process.stdout.write("No avatar sources found in /workspace/avatar-src\n");
    return;
  }
  for (const file of written) {
    process.stdout.write(`${file}\n`);
  }
}

const invokedDirectly = process.argv[1]?.endsWith("build-avatars.ts");

if (invokedDirectly) {
  main().catch((error: unknown) => {
    const message =
      error instanceof Error ? error.message : "Avatar generation failed";
    process.stderr.write(`${message}\n`);
    process.exitCode = 1;
  });
}
